def pages():
 if hashlib.sha256(PDF.read_bytes()).hexdigest()!=EXPECTED: raise SystemExit('PDF не совпадает с проверенным источником: границы решений не применены.')
 out={}
 for p in range(1,90):
  x=subprocess.run(['pdftotext','-f',str(p),'-l',str(p),'-raw',str(PDF),'-'],capture_output=True,text=True,check=True).stdout
  # Удаляем только первую строку-колонтитул PDF, не содержание решения.
  x=re.sub(r'^.*?(?:18[89][0-9]{2}|1896).*?\n','',x,count=1)
  out[p]=x.replace('\f','')
 return out

def pos(text,marker):
 if marker is None:return 0
 i=text.find(marker)
 if i<0: raise ValueError(f'Не найдено начало {marker!r}')
 return i

def clean(s): return re.sub(r'\s+',' ',s.replace('\u00ad','')).strip()
def main():
 global PDF, OUT
 parser=argparse.ArgumentParser(description='Собрать 1896 из проверенного FineReader PDF.')
 parser.add_argument('--pdf', required=True, type=Path, help='локальный PDF FineReader (в Git не добавляется)')
 parser.add_argument('--out', type=Path, default=OUT, help='путь к volume.txt')
 args=parser.parse_args()
 PDF=args.pdf; OUT=args.out
 pg=pages(); starts=[]
 for n,p,mark in STARTS: starts.append((n,p,pos(pg[p],mark)))
 source=[]
 for k,(n,p,o) in enumerate(starts):
  ep,eo=(starts[k+1][1],starts[k+1][2]) if k+1<len(starts) else (89,len(pg[89]))
  parts=[]
  for page in range(p,ep+1):
   a=o if page==p else 0; b=eo if page==ep else len(pg[page]); parts.append(pg[page][a:b])
  source.append(clean(' '.join(parts)))
 out=['РѢШЕНІЯ ОБЩАГО СОБРАНІЯ ПЕРВАГО И КАССАЦІОННЫХЪ ДЕПАРТАМЕНТОВЪ ПРАВИТЕЛЬСТВУЮЩАГО СЕНАТА. 1896 г.',
      'Текстъ извлечён изъ локальнаго PDF ABBYY FineReader. Орѳографія и ошибки OCR сохранены; номера и даты рѣшеній сверены по изображениямъ PDF.']
 for n,date,text in zip(range(1,50),DATES,source):
  flat=clean(text)
  original_head=re.sub(r'^.*?\b18(?:95|96)\b.*?дн[яй]\.?\s*','',flat,count=1,flags=re.I)
  original_head=re.split(r'\(?Предс[ѣе]|Выслушавъ|По выслушаніи',original_head,maxsplit=1,flags=re.I)[0].strip()
  if n in (40,46): original_head='Заголовокъ частично отсутствуетъ въ текстовомъ слоѣ PDF; см. исходный сканъ.'
  head=original_head[:900] if original_head else 'Заголовокъ не извлечён автоматическимъ распознаніемъ.'
  out.extend([f'{n}. {date}. {head}', 'Предсѣдательствовалъ: составъ присутствія см. въ первоисточникѣ.', text])
 OUT.parent.mkdir(parents=True,exist_ok=True);OUT.write_text('\n\n'.join(out)+'\n',encoding='utf8')
 print(OUT,len(source),OUT.stat().st_size)
if __name__=='__main__':main()
